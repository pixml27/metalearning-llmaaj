"""Validated inputs, durable artifacts, schemas and restart contracts."""
from contextlib import contextmanager
from datetime import datetime, timezone
from importlib.metadata import version
from pathlib import Path
from typing import Literal
import csv
import fcntl
import hashlib
import json
import os
import platform

from pydantic import BaseModel, ConfigDict, Field
from src.common import BASE_FIELDS, TOPICS, load_dataset

ROOT = Path(__file__).resolve().parents[1]
PROMPTS = Path(__file__).resolve().parent / "prompts"
ARTIFACT_VERSION = 2


class SolutionError(ValueError):
    """A safe, actionable message generated by our own validation."""


def utc_now():
    return datetime.now(timezone.utc).isoformat()


def digest(value: str | bytes):
    return hashlib.sha256(value.encode() if isinstance(value, str) else value).hexdigest()


def canonical(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False)


def atomic_text(path: Path, text: str):
    temporary = path.with_name(path.name + ".tmp")
    with temporary.open("w", encoding="utf-8", newline="") as stream:
        stream.write(text)
        stream.flush()
        os.fsync(stream.fileno())
    temporary.replace(path)


def write_json(path: Path, value):
    atomic_text(path, json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + "\n")


def append_jsonl(path: Path, value):
    with path.open("a", encoding="utf-8") as stream:
        stream.write(canonical(value) + "\n")
        stream.flush()
        os.fsync(stream.fileno())


def read_jsonl(path: Path):
    if not path.exists():
        return []
    # Never silently discard a corrupt ledger or partially written response.
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def read_inputs(path: Path, *, labeled: bool):
    if path.suffix.lower() != ".jsonl":
        raise SolutionError("Use JSONL from src/prepare_inputs.py")
    rows = load_dataset(path, require_labels=labeled)
    fields = BASE_FIELDS | ({"label"} if labeled else set())
    if any(set(row) != fields for row in rows):
        raise SolutionError("Expected exactly item_id,topic,context,conversation" + (",label" if labeled else "; eval inputs must be unlabeled"))
    return rows


def judge_payload(row):
    # Gold, IDs, topic and alternative translations never enter the judge request.
    return {"context": row["context"], "conversation": row["conversation"]}


class StrictModel(BaseModel):
    model_config = ConfigDict(extra="forbid")


class Judgment(StrictModel):
    label: Literal["good", "bad"]


class CaseAnalysis(StrictModel):
    comment_a: str = Field(min_length=1, max_length=1800)
    comment_b: str = Field(min_length=1, max_length=1500)


class TopicAdvice(StrictModel):
    credit: str = Field(min_length=1, max_length=5000)
    financial_position: str = Field(min_length=1, max_length=5000)
    savings: str = Field(min_length=1, max_length=5000)
    spending: str = Field(min_length=1, max_length=5000)


class PromptArtifact(StrictModel):
    base_prompt: str = Field(min_length=1, max_length=24000)
    topic_advice: TopicAdvice


def compiled_prompts(artifact: PromptArtifact):
    definitions = prompt_text("definitions.md")
    return {topic: artifact.base_prompt.strip() + "\n\n" + definitions
            + f"\n\nTopic: {topic}\nTopic-specific advice:\n"
            + getattr(artifact.topic_advice, topic).strip() for topic in TOPICS}


def prompt_text(name):
    return (PROMPTS / name).read_text(encoding="utf-8").strip()


def runtime_fingerprint():
    paths = [*Path(__file__).parent.glob("*.py"), *PROMPTS.glob("*.md"), ROOT / "src/common.py",
             ROOT / "requirements.lock.txt"]
    return {"python": platform.python_version(),
            "packages": {name: version(name) for name in (
                "litellm", "pydantic-ai-litellm", "pydantic-ai-slim", "pydantic", "python-dotenv")},
            "sources": {str(path.relative_to(ROOT)): digest(path.read_bytes()) for path in sorted(paths)}}


@contextmanager
def directory_lock(directory: Path, *, shared=False):
    path = directory / ".run.lock"
    # eval can consume a read-only artifacts volume; adapt has already created this file.
    with path.open("r" if shared else "a", encoding="utf-8") as stream:
        try:
            fcntl.flock(stream, (fcntl.LOCK_SH if shared else fcntl.LOCK_EX) | fcntl.LOCK_NB)
        except BlockingIOError:
            raise SolutionError("This directory is in use by another run") from None
        yield


def frozen_manifest(directory: Path, config):
    path = directory / "manifest.json"
    expected = digest(canonical(config))
    if path.exists():
        existing = json.loads(path.read_text(encoding="utf-8"))
        if existing.get("config_sha256") != expected or existing.get("config") != config:
            raise SolutionError("Input, code or configuration changed; use a fresh output directory")
        return existing
    if any(path.name != ".run.lock" for path in directory.iterdir()):
        raise SolutionError("A new run requires an empty output directory")
    manifest = {"artifact_version": ARTIFACT_VERSION, "config": config,
                "config_sha256": expected, "created_at": utc_now()}
    write_json(path, manifest)
    return manifest


def save_predictions(path: Path, rows, labels):
    if set(labels) != {row["item_id"] for row in rows} or any(value not in {"good", "bad"} for value in labels.values()):
        raise SolutionError("Predictions must cover every input ID exactly once")
    temporary = path.with_name(path.name + ".tmp")
    with temporary.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=["item_id", "label"])
        writer.writeheader()
        writer.writerows({"item_id": row["item_id"], "label": labels[row["item_id"]]} for row in rows)
        stream.flush()
        os.fsync(stream.fileno())
    temporary.replace(path)


def load_artifact(directory: Path):
    summary = json.loads((directory / "summary.json").read_text(encoding="utf-8"))
    if summary.get("status") != "complete" or summary.get("artifact_version") != ARTIFACT_VERSION:
        raise SolutionError("Adaptation is incomplete or uses an unsupported artifact version")
    required = {"artifact.json", "routed_prompts.json", "explanation.md", "explanation.json", "manifest.json", "budget.jsonl",
                "linked_artifact.json", "definitions.md"}
    files = summary.get("files_sha256", {})
    if not required <= set(files):
        raise SolutionError("Adaptation summary is missing required artifacts")
    for name in required:
        if files[name] != digest((directory / name).read_bytes()):
            raise SolutionError(f"Adaptation file was modified: {name}")
    if (directory / "definitions.md").read_text(encoding="utf-8").strip() != prompt_text("definitions.md"):
        raise SolutionError("Saved definitions disagree with the runtime; use matching solution code")
    artifact = PromptArtifact.model_validate_json((directory / "artifact.json").read_text(encoding="utf-8"))
    prompts = json.loads((directory / "routed_prompts.json").read_text(encoding="utf-8"))
    if prompts != compiled_prompts(artifact):
        raise SolutionError("Compiled prompts disagree with the learned artifact")
    return artifact, prompts, summary
